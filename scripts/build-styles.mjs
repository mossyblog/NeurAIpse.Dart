import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

mkdirSync("dist", { recursive: true });

const tailwindBin = path.resolve(
  "node_modules/.bin",
  process.platform === "win32" ? "tailwindcss.cmd" : "tailwindcss",
);

execFileSync(
  tailwindBin,
  ["-i", "src/ui/styles.css", "-o", "dist/styles.css", "--minify"],
  {
    stdio: "inherit",
    shell: process.platform === "win32",
  },
);

const compiledCss = readFileSync("dist/styles.css", "utf8");

const declarations = [];
const shadowCssWithoutProperties = compiledCss.replace(
  /@property\s+(--[\w-]+)\s*\{([^}]*)\}/g,
  (_match, name, body) => {
    const syntaxMatch = body.match(/syntax\s*:\s*([^;]+)/);
    const initialMatch = body.match(/initial-value\s*:\s*([^;]+)/);
    let initialValue = initialMatch ? initialMatch[1].trim() : "initial";
    if (syntaxMatch && syntaxMatch[1].includes("<length>") && initialValue === "0") {
      initialValue = "0px";
    }
    declarations.push(`${name}:${initialValue}`);
    return "";
  },
);

const shadowCss =
  declarations.length > 0
    ? `${shadowCssWithoutProperties}@layer properties{:host,*,::before,::after,::backdrop{${declarations.join(";")}}}`
    : shadowCssWithoutProperties;

writeFileSync(
  "src/ui/surface-css.generated.ts",
  `// Generated by scripts/build-styles.mjs. Do not edit by hand.\nexport const SURFACE_CSS: string = ${JSON.stringify(shadowCss)};\n`,
  "utf8",
);
